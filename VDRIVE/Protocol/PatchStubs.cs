        // The write switch, after the last ",W":
        //   ""  "9"  "8D2"   the stub: drive (8 when not given), disk of the set (1 when not given);
        //                    "@" on the end ("@", "9@", "8D2@") writes again what is already on the drive
        //   "1A"  "2C"  "A"  a slice: disk (1 when not given), slice A..Z
        // slice = -1 for a stub. false when the name has no write switch.
        private static readonly Regex WriteStubSwitch = new Regex(@"^(?<dev>\d{1,2})?(?:D(?<disk>[1-9]))?(?<force>@)?$", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
        private static readonly Regex WriteSliceSwitch = new Regex(@"^(?<disk>[1-9])?(?<slice>[A-Z])$", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

        public static bool TryGetWrite(string fileName, out byte device, out int disk, out int slice, out bool force)
        {
            force = false;
            device = 8;
            disk = 1;
            slice = -1;
            if (fileName == null) return false;
            int at = fileName.LastIndexOf(",W", StringComparison.OrdinalIgnoreCase);
            if (at < 0) return false;
            string rest = fileName.Substring(at + 2);

            Match m = WriteSliceSwitch.Match(rest);
            if (m.Success)
            {
                if (m.Groups["disk"].Success) disk = m.Groups["disk"].Value[0] - '0';
                slice = char.ToUpperInvariant(m.Groups["slice"].Value[0]) - 'A';
                return true;
            }
            m = WriteStubSwitch.Match(rest);
            if (!m.Success) return false;
            if (m.Groups["dev"].Success)
            {
                int d = int.Parse(m.Groups["dev"].Value);
                if (d < 8 || d > 30) return false;
                device = (byte)d;
            }
            if (m.Groups["disk"].Success) disk = m.Groups["disk"].Value[0] - '0';
            force = m.Groups["force"].Success;
            return true;
        }


        // The write stub for disk number "disk" (1-based) of a set (one path for a single disk): its names
        // and drive commands, the next disk's stub to chain to, and - on the last disk - the swap list.
        // first: the set's first disk (the game starts from it); image: the disk being written.
        public static byte[] BuildWriteStub(IReadOnlyList<string> setPaths, int disk, byte device, byte[] image, byte[] first, bool force = false)
        {
            int count = setPaths.Count;
            if (count < 1 || count > 9 || disk < 1 || disk > count) throw new ArgumentException("disk set not supported");
            int slices = (image.Length + WriteSliceSize - 1) / WriteSliceSize;
            if (slices < 1 || slices > 26) throw new ArgumentException("image size not supported");
            int lastLength = image.Length - (slices - 1) * WriteSliceSize;

            string name = DiskDriveName(setPaths, disk - 1);
            var prg = new List<byte> { (byte)(WriteStubAddress & 0xFF), (byte)(WriteStubAddress >> 8) };
            prg.AddRange(WriteStub);
            byte[] stub = prg.ToArray();
            stub[2 + WriteDeviceOffset] = device;
            stub[2 + WriteSlicesOffset] = (byte)slices;
            stub[2 + WriteLastLenOffset] = (byte)(lastLength & 0xFF);
            stub[2 + WriteLastLenOffset + 1] = (byte)(lastLength >> 8);
            PutString(stub, WriteMkdirOffset, "MD//" + WriteFolder);        // from the card's root: works from anywhere,
            PutString(stub, WriteCdFolderOffset, "CD//" + WriteFolder);     // even inside an image or the folder itself
            PutString(stub, WriteCheckOffset, name + ".D64,P,R");
            PutString(stub, WriteOpenOffset, "@:" + name + ".TMP,P,W");
            PutString(stub, WriteRenameOffset, "R:" + name + ".D64=" + name + ".TMP");
            PutString(stub, WriteScratchOffset, "S:" + name + ".D64");
            stub[2 + WriteForceOffset] = force ? (byte)1 : (byte)0;
            PutString(stub, WriteAppendOffset, name + ".TMP,P,A");     // slices after the first: appended
            stub[2 + WriteSliceDiskOffset] = (byte)('0' + disk);       // "*,W<disk>A"
            stub[2 + WriteRunOffset] = WriteRunMode(first);
            PutString(stub, WriteLabelOffset, count > 1 ? $"DISK {disk}/{count} " : "");

            if (disk < count)
            {
                stub[2 + WriteNextOffset] = (byte)(disk + 1);
                PutString(stub, WriteChainOffset, $"*,W{device}D{disk + 1}" + (force ? "@" : ""));
            }
            else if (count > 1)
            {
                // the swap list: the SD2IEC mounts its first disk on XS, and its button steps through them
                string listName = SetListName(setPaths);
                string list = string.Concat(Enumerable.Range(0, count).Select(i => "//" + WriteFolder.ToLowerInvariant() + "/:" + DiskDriveName(setPaths, i).ToLowerInvariant() + ".d64\n"));
                byte[] listBytes = System.Text.Encoding.ASCII.GetBytes(list);
                if (listBytes.Length > 255) throw new ArgumentException("swap list too long");
                PutString(stub, WriteListOpenOffset, "@:" + listName + ",P,W");     // PRG: no x00 wrapper on the card
                stub[2 + WriteListLengthOffset] = (byte)listBytes.Length;
                Array.Copy(listBytes, 0, stub, 2 + WriteListOffset, listBytes.Length);
                PutString(stub, WriteCdImageOffset, "XS:" + listName);
            }
            else
            {
                PutString(stub, WriteCdImageOffset, "CD:" + name + ".D64");
            }
            return stub;
        }


        // After mounting: start the first file like LOAD"*",8,1 would - RUN it when it loads at $0801
        // (a BASIC start, nearly every game), else load it and stop at READY. 0 = no file: just stop.
        public static byte WriteRunMode(byte[] image)
        {
            int? loadAddress = FirstFileLoadAddress(image);
            if (loadAddress == null) return 0;
            return loadAddress == BasicStart ? (byte)1 : (byte)2;
        }

        // The load address of the first file in a D64's directory (what LOAD"*" loads), or null
        private static int? FirstFileLoadAddress(byte[] image)
        {
            if (image == null || image.Length < 174848) return null;
            int dir = D64Offset(18, 1);
            for (int e = 0; e < 8; e++)
            {
                int entry = dir + e * 32;
                byte type = image[entry + 2];
                if ((type & 0x07) == 0) continue;                    // deleted / empty
                if ((type & 0x07) != 2) return null;                 // first file is not a PRG
                int track = image[entry + 3], sector = image[entry + 4];
                if (track < 1 || track > 35) return null;
                int data = D64Offset(track, sector);
                return image[data + 2] | (image[data + 3] << 8);
            }
            return null;
        }

        private static int D64Offset(int track, int sector)
        {
            int offset = 0;
            for (int t = 1; t < track; t++)
                offset += t <= 17 ? 21 : t <= 24 ? 19 : t <= 30 ? 18 : 17;
            return (offset + sector) * 256;
        }

        // One slice of the image as a PRG for the stub's buffer (null past the end)
        public static byte[] BuildWriteSlice(byte[] image, int slice)
        {
            int start = slice * WriteSliceSize;
            if (slice < 0 || start >= image.Length) return null;
            int length = Math.Min(WriteSliceSize, image.Length - start);
            byte[] prg = new byte[2 + length];
            prg[0] = (byte)(WriteBufferAddress & 0xFF);
            prg[1] = (byte)(WriteBufferAddress >> 8);
            Array.Copy(image, start, prg, 2, length);
            return prg;
        }

        // The image's name on the drive: up to 7 letters/digits of its own name, then 4 hex digits of its
        // path, so two images with the same start never share a file ("MORDONS-3F2A"). With ".D64" that
        // is 16 characters at most, the longest name a C64 can send.
        public static string DriveName(string imagePath)
        {
            string baseName = new string(Path.GetFileNameWithoutExtension(imagePath ?? "")
                .ToUpperInvariant().Where(c => (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')).Take(7).ToArray());
            if (baseName.Length == 0) baseName = "DISK";
            uint hash = 2166136261;                                    // FNV-1a over the full path
            foreach (char c in (imagePath ?? "").ToUpperInvariant())
            {
                hash ^= c;
                hash *= 16777619;
            }
            return $"{baseName}-{(hash ^ (hash >> 16)) & 0xFFFF:X4}";
        }

        // A disk of a set on the drive: the disk number goes into the name, so the disks can be told apart
        // ("CALIFO1-8920", "CALIFO2-9F83"); a single disk keeps DriveName. 16 characters at most with ".D64".
        public static string DiskDriveName(IReadOnlyList<string> setPaths, int index)
        {
            if (setPaths.Count < 2) return DriveName(setPaths[index]);
            string full = DriveName(setPaths[index]);                  // "CALIFOR-8920"
            string baseName = full.Substring(0, full.LastIndexOf('-'));
            if (baseName.Length > 6) baseName = baseName.Substring(0, 6);
            return baseName + (index + 1) + full.Substring(full.LastIndexOf('-'));
        }

        // The set's swap list: its base name and disk 1's code ("CALIFO-8920.LST")
        public static string SetListName(IReadOnlyList<string> setPaths)
        {
            string full = DriveName(setPaths[0]);
            int dash = full.LastIndexOf('-');
            string baseName = full.Substring(0, dash);
            if (baseName.Length > 6) baseName = baseName.Substring(0, 6);
            return baseName + full.Substring(dash) + ".LST";
        }

        private static void PutString(byte[] stub, int offset, string text)
        {
            byte[] bytes = System.Text.Encoding.ASCII.GetBytes(text);
            if (bytes.Length > WriteStringSize - 1) throw new ArgumentException("drive command too long: " + text);
            stub[2 + offset] = (byte)bytes.Length;
            Array.Copy(bytes, 0, stub, 2 + offset + 1, bytes.Length);
        }

        private static void AddSegment(List<byte> data, int address, byte[] bytes)
        {
            int count = (0x10000 - bytes.Length) & 0xFFFF;   // the stub counts up to 0
            data.Add((byte)(address & 0xFF));
            data.Add((byte)(address >> 8));
            data.Add((byte)(count & 0xFF));
            data.Add((byte)(count >> 8));
            data.AddRange(bytes);
        }
