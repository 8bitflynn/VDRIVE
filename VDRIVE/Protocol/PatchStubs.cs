        // The write switch, after the last ",W":
        //   ""  "9"  "8D2"   the stub: drive (8 when not given), disk of the set (1 when not given);
        //                    "@" on the end ("@", "9@", "8D2@") writes again what is already on the drive
        //   "1A"  "2C"  "A"  a slice: disk (1 when not given), slice A..Z
        // slice = -1 for a stub. false when the name has no write switch.
        private static readonly Regex WriteStubSwitch = new Regex(@"^(?<dev>\d{1,2})?(?:D(?<disk>[1-9]))?(?<force>@)?$", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
        private static readonly Regex WriteSliceSwitch = new Regex(@"^(?<disk>[1-9])?(?<slice>[A-Z])$", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

        public static bool TryGetWrite(string fileName, out byte device, out int disk, out int slice, out bool force)
        {
            force = false;
            device = 8;
            disk = 1;
            slice = -1;
            if (fileName == null) return false;
            int at = fileName.LastIndexOf(",W", StringComparison.OrdinalIgnoreCase);
            if (at < 0) return false;
            string rest = fileName.Substring(at + 2);

            Match m = WriteSliceSwitch.Match(rest);
            if (m.Success)
            {
                if (m.Groups["disk"].Success) disk = m.Groups["disk"].Value[0] - '0';
                slice = char.ToUpperInvariant(m.Groups["slice"].Value[0]) - 'A';
                return true;
            }
            m = WriteStubSwitch.Match(rest);
            if (!m.Success) return false;
            if (m.Groups["dev"].Success)
            {
                int d = int.Parse(m.Groups["dev"].Value);
                if (d < 8 || d > 30) return false;
                device = (byte)d;
            }
            if (m.Groups["disk"].Success) disk = m.Groups["disk"].Value[0] - '0';
            force = m.Groups["force"].Success;
            return true;
        }


        // The write stub for disk number "disk" (1-based) of a set (one path for a single disk): its names
        // and drive commands, the next disk's stub to chain to, and - on the last disk - the swap list.
        // first: the set's first disk (the game starts from it); image: the disk being written.
        public static byte[] BuildWriteStub(IReadOnlyList<string> setPaths, int disk, byte device, byte[] image, byte[] first, bool force = false, string folder = null, string identity = null)
        {
            string WriteFolder = WriteFolderOrDefault(folder);
            int count = setPaths.Count;
            if (count < 1 || count > 9 || disk < 1 || disk > count) throw new ArgumentException("disk set not supported");
            int slices = (image.Length + WriteSliceSize - 1) / WriteSliceSize;
            if (slices < 1 || slices > 26) throw new ArgumentException("image size not supported");
            int lastLength = image.Length - (slices - 1) * WriteSliceSize;

            string name = DiskDriveName(setPaths, disk - 1, identity);
            var prg = new List<byte> { (byte)(WriteStubAddress & 0xFF), (byte)(WriteStubAddress >> 8) };
            prg.AddRange(WriteStub);
            byte[] stub = prg.ToArray();
            stub[2 + WriteDeviceOffset] = device;
            stub[2 + WriteSlicesOffset] = (byte)slices;
            stub[2 + WriteLastLenOffset] = (byte)(lastLength & 0xFF);
            stub[2 + WriteLastLenOffset + 1] = (byte)(lastLength >> 8);
            // from the root ("//"): works from anywhere, even inside an image or the folder itself. CMD path forms that
            // IDEDOS (IDE64) and the SD2IEC both take: MD//:NAME makes NAME in the root, CD//NAME/ goes into it
            // (IDEDOS took "CD//:NAME" too, but stayed in the root)
            PutString(stub, WriteMkdirOffset, "MD//:" + WriteFolder);
            PutString(stub, WriteCdFolderOffset, "CD//" + WriteFolder + "/");
            PutString(stub, WriteCheckOffset, name + ".D64,P,R");
            PutString(stub, WriteOpenOffset, "@:" + name + ".TMP,P,W");
            PutString(stub, WriteRenameOffset, "R:" + name + ".D64=" + name + ".TMP");
            PutString(stub, WriteScratchOffset, "S:" + name + ".D64");
            stub[2 + WriteForceOffset] = force ? (byte)1 : (byte)0;
            PutString(stub, WriteAppendOffset, name + ".TMP,P,A");     // slices after the first: appended
            stub[2 + WriteSliceDiskOffset] = (byte)('0' + disk);       // "*,W<disk>A"
            stub[2 + WriteRunOffset] = WriteRunMode(first);
            // the program the stub starts: the first PRG by name (LOAD"*" would take a separator line before it)
            byte[] runName = FirstPrg(first, out _) ?? new byte[] { (byte)'*' };
            stub[2 + WriteRunNameOffset] = (byte)runName.Length;
            Array.Copy(runName, 0, stub, 2 + WriteRunNameOffset + 1, runName.Length);
            PutString(stub, WriteLabelOffset, count > 1 ? $"DISK {disk}/{count} " : "");
            // how many empty sectors each slice has: the stub finds a packed slice by this (BuildWriteSlice)
            for (int s = 0; s < slices; s++) stub[2 + WriteFillsOffset + s] = (byte)CountEmptySectors(image, s);

            if (disk < count)
            {
                stub[2 + WriteNextOffset] = (byte)(disk + 1);
                PutString(stub, WriteChainOffset, $"*,W{device}D{disk + 1}" + (force ? "@" : ""));
            }
            else if (count > 1)
            {
                // the swap list: the SD2IEC mounts its first disk on XS, and its button steps through them
                string listName = SetListName(setPaths, identity);
                string list = string.Concat(Enumerable.Range(0, count).Select(i => "//" + WriteFolder.ToLowerInvariant() + "/:" + DiskDriveName(setPaths, i, identity).ToLowerInvariant() + ".d64\n"));
                byte[] listBytes = System.Text.Encoding.ASCII.GetBytes(list);
                if (listBytes.Length > 255) throw new ArgumentException("swap list too long");
                PutString(stub, WriteListOpenOffset, "@:" + listName + ",P,W");     // PRG: no x00 wrapper on the card
                stub[2 + WriteListLengthOffset] = (byte)listBytes.Length;
                Array.Copy(listBytes, 0, stub, 2 + WriteListOffset, listBytes.Length);
                PutString(stub, WriteCdImageOffset, "XS:" + listName);
            }
            else
            {
                PutString(stub, WriteCdImageOffset, "CD:" + name + ".D64");
            }
            return stub;
        }


        // A single program instead of a disk image ("*,W12" with a PRG mounted): copied to the drive's VDRIVE folder under
        // its own name (PrgDriveName), load address and all, then loaded back from there (and RUN if it's BASIC). It goes
        // to a temporary file first and is renamed at the end, like a disk image, so an interrupted copy never leaves half
        // a program.
        public const string WritePrgTempName = "VDRIVE.TMP";
        public static byte[] BuildWritePrgStub(string fileName, byte device, byte[] prg, bool force = false, string folder = null, string driveName = null)
        {
            string WriteFolder = WriteFolderOrDefault(folder);
            int slices = (prg.Length + WriteSliceSize - 1) / WriteSliceSize;
            if (slices < 1 || slices > 26) throw new ArgumentException("program size not supported");
            int lastLength = prg.Length - (slices - 1) * WriteSliceSize;

            // always NAME.PRG: on a FAT card (SD2IEC, IDE64) a file without the extension isn't a program to LOAD
            string name = PrgFileName(driveName ?? PrgDriveName(fileName));
            var bytes = new List<byte> { (byte)(WriteStubAddress & 0xFF), (byte)(WriteStubAddress >> 8) };
            bytes.AddRange(WriteStub);
            byte[] stub = bytes.ToArray();
            stub[2 + WriteDeviceOffset] = device;
            stub[2 + WriteSlicesOffset] = (byte)slices;
            stub[2 + WriteLastLenOffset] = (byte)(lastLength & 0xFF);
            stub[2 + WriteLastLenOffset + 1] = (byte)(lastLength >> 8);
            PutString(stub, WriteMkdirOffset, "MD//:" + WriteFolder);
            PutString(stub, WriteCdFolderOffset, "CD//" + WriteFolder + "/");
            PutString(stub, WriteCheckOffset, name + ",P,R");
            PutString(stub, WriteOpenOffset, "@:" + WritePrgTempName + ",P,W");
            PutString(stub, WriteRenameOffset, "R:" + name + "=" + WritePrgTempName);
            PutString(stub, WriteScratchOffset, "S:" + name);
            stub[2 + WriteForceOffset] = force ? (byte)1 : (byte)0;
            PutString(stub, WriteAppendOffset, WritePrgTempName + ",P,A");
            stub[2 + WriteSliceDiskOffset] = (byte)'1';
            // then loaded back from the drive, the way a disk's game starts: RUN for a BASIC program ($0801, like
            // Goblin's SYS 2061 line), otherwise LOAD"NAME",dev,1 and READY. (its SYS is the user's)
            int loadAddress = prg.Length >= 2 ? prg[0] | prg[1] << 8 : 0;
            stub[2 + WriteRunOffset] = loadAddress < 0x0200 ? (byte)3 : loadAddress == 0x0801 ? (byte)1 : (byte)2;
            byte[] runName = System.Text.Encoding.ASCII.GetBytes(name);
            stub[2 + WriteRunNameOffset] = (byte)runName.Length;
            Array.Copy(runName, 0, stub, 2 + WriteRunNameOffset + 1, runName.Length);
            PutString(stub, WriteLabelOffset, "");
            stub[2 + WritePrgOffset] = 1;
            return stub;
        }

        // The program's file on the drive: its name (at most 12 characters) + ".PRG" - 16 in all, the most a C64 file
        // name holds, like the disk images' "CALIFOR-37FD.D64". "GOBLIN POND SOFT" -> "GOBLIN POND.PRG"
        public static string PrgFileName(string driveName)
        {
            string name = (driveName ?? "").Trim();
            if (name.Length > 12) name = name.Substring(0, 12).TrimEnd();
            return (name.Length == 0 ? "PROGRAM" : name) + ".PRG";
        }

        // A program's name on the drive: its file name without the extension, in capitals, only characters every DOS
        // takes in a name (no , : * ? = @ / or quotes), at most 16 - "Larry-WiC64meX - Demo.prg" -> "LARRY-WIC64MEX -"
        // (written as PrgFileName: the first 12 + ".PRG")
        public static string PrgDriveName(string fileName)
        {
            string name = Path.GetFileNameWithoutExtension(fileName ?? "").ToUpperInvariant();
            var kept = new System.Text.StringBuilder();
            foreach (char c in name)
            {
                if ((c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == ' ' || c == '.' || c == '-' || c == '_' || c == '+' || c == '!')
                    kept.Append(c);
            }
            string result = System.Text.RegularExpressions.Regex.Replace(kept.ToString(), " {2,}", " ").Trim();
            if (result.Length > 16) result = result.Substring(0, 16).TrimEnd();
            return result.Length == 0 ? "PROGRAM" : result;
        }

        // A program made on the server (a SID converted by psid64: always "c64sid.prg") is named after what it is:
        // up to 7 characters of its title, then 4 hex digits of the whole title, like the D64 names - every song
        // gets its own file and the "already there?" check only skips one written before. 12 in all, so ".PRG" fits.
        // "COMMANDO - ROB HUBBARD" -> "COMMAND-1A2B" (on the drive: COMMAND-1A2B.PRG)
        public static string TitleDriveName(string title)
        {
            string upper = (title ?? "").ToUpperInvariant();
            var kept = new System.Text.StringBuilder();
            foreach (char c in upper)
            {
                if ((c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == ' ' || c == '.' || c == '_' || c == '+' || c == '!')
                    kept.Append(c);
                else if (c == '-') kept.Append(' ');                  // the dash belongs to the code
            }
            string baseName = System.Text.RegularExpressions.Regex.Replace(kept.ToString(), " {2,}", " ").Trim();
            if (baseName.Length > 7) baseName = baseName.Substring(0, 7).TrimEnd();
            if (baseName.Length == 0) baseName = "PROGRAM";
            uint hash = 2166136261;                                    // FNV-1a over the whole title
            foreach (char c in upper)
            {
                hash ^= c;
                hash *= 16777619;
            }
            return $"{baseName}-{(hash ^ (hash >> 16)) & 0xFFFF:X4}";
        }

        // After mounting: start the first file like LOAD"*",8,1 would - RUN it when it loads at $0801
        // (a BASIC start, nearly every game), else load it and stop at READY. 0 = no file: just stop.
        public static byte WriteRunMode(byte[] image)
        {
            if (FirstPrg(image, out int loadAddress) == null) return 0;
            if (loadAddress < 0x0200) return 3;    // into the stack page (GEOS): LOAD typed for BASIC (patch_write.asm)
            return loadAddress == BasicStart ? (byte)1 : (byte)2;
        }

        // The first PRG in a D64's directory: its name (as on the disk, without the $A0 padding) and load address.
        // Separator lines (USR/SEQ/DEL, often "----------------") are skipped. null when there is no PRG.
        private static byte[] FirstPrg(byte[] image, out int loadAddress)
        {
            loadAddress = 0;
            if (image == null || image.Length < 174848) return null;
            int track = 18, sector = 1;
            for (int hops = 0; track >= 1 && track <= 35 && hops < 18; hops++)
            {
                int dir = D64Offset(track, sector);
                for (int e = 0; e < 8; e++)
                {
                    int entry = dir + e * 32;
                    byte type = image[entry + 2];
                    if ((type & 0x80) == 0 || (type & 0x07) != 2) continue;     // not a closed PRG
                    int t = image[entry + 3], s = image[entry + 4];
                    if (t < 1 || t > 35) continue;
                    byte[] name = image.Skip(entry + 5).Take(16).TakeWhile(c => c != 0xA0).ToArray();
                    if (name.Length == 0) continue;
                    int data = D64Offset(t, s);
                    loadAddress = image[data + 2] | (image[data + 3] << 8);
                    return name;
                }
                track = image[dir]; sector = image[dir + 1];
            }
            return null;
        }

        private static int D64Offset(int track, int sector)
        {
            int offset = 0;
            for (int t = 1; t < track; t++)
                offset += t <= 17 ? 21 : t <= 24 ? 19 : t <= 30 ? 18 : 17;
            return (offset + sector) * 256;
        }

        // One slice of the image as a PRG for the stub's buffer (null past the end)
        // A slice of a disk image, as a PRG for the stub's buffer. pack (disk images, not single programs): a slice
        // with empty sectors - 256 bytes of one value, mostly unused blocks full of $00 - goes packed, and the stub
        // expands it (patch_write.asm, unpack). Packed: [16 bytes, a bit per sector (bit s%8 of byte s/8), 1 = empty]
        // [the sectors in order: an empty one as its one byte, the others as they are], loaded so it ends where the
        // slice ends ($1000 + length): at $0FF0 + 255 x (empty sectors). The stub's table (BuildWriteStub) has that
        // count, so it knows where the data starts; expanding forward from $1000, its output never runs into data it
        // hasn't read yet. A slice without an empty sector goes as it is, to $1000.
        public static byte[] BuildWriteSlice(byte[] image, int slice, bool pack = false)
        {
            int start = slice * WriteSliceSize;
            if (slice < 0 || start >= image.Length) return null;
            int length = Math.Min(WriteSliceSize, image.Length - start);
            int empty = pack ? CountEmptySectors(image, slice) : 0;
            if (empty == 0)
            {
                byte[] prg = new byte[2 + length];
                prg[0] = (byte)(WriteBufferAddress & 0xFF);
                prg[1] = (byte)(WriteBufferAddress >> 8);
                Array.Copy(image, start, prg, 2, length);
                return prg;
            }

            int sectors = (length + 255) / 256;
            var packed = new List<byte>(2 + WritePackBits + length - 255 * empty);
            int address = WriteBufferAddress - WritePackBits + 255 * empty;
            packed.Add((byte)(address & 0xFF));
            packed.Add((byte)(address >> 8));
            byte[] bits = new byte[WritePackBits];
            for (int s = 0; s < sectors; s++)
                if (IsEmptySector(image, start, length, s)) bits[s >> 3] |= (byte)(1 << (s & 7));
            packed.AddRange(bits);
            for (int s = 0; s < sectors; s++)
            {
                int at = start + s * 256;
                if (IsEmptySector(image, start, length, s)) packed.Add(image[at]);
                else packed.AddRange(new ArraySegment<byte>(image, at, Math.Min(256, start + length - at)));
            }
            if (address + packed.Count - 2 != WriteBufferAddress + length)
                throw new InvalidOperationException("packed slice doesn't end where the slice ends");
            return packed.ToArray();
        }

        private const int WritePackBits = 16;              // 128 sectors (32K) a bit each

        // empty sectors in a slice: whole 256-byte sectors of one value (a short last sector never counts)
        public static int CountEmptySectors(byte[] image, int slice)
        {
            int start = slice * WriteSliceSize;
            if (slice < 0 || start >= image.Length) return 0;
            int length = Math.Min(WriteSliceSize, image.Length - start);
            int empty = 0;
            for (int s = 0; s < (length + 255) / 256; s++) if (IsEmptySector(image, start, length, s)) empty++;
            return empty;
        }

        private static bool IsEmptySector(byte[] image, int sliceStart, int sliceLength, int sector)
        {
            int at = sliceStart + sector * 256;
            if (sector * 256 + 256 > sliceLength) return false;
            byte value = image[at];
            for (int i = 1; i < 256; i++) if (image[at + i] != value) return false;
            return true;
        }

        // The image's name on the drive: up to 7 letters/digits of its own name, then 4 hex digits of where it
        // came from, so two images with the same start never share a file ("MORDONS-3F2A"). With ".D64" that
        // is 16 characters at most, the longest name a C64 can send.
        // identity: for a disk downloaded into a session's work folder (Commodore.Software, HVSC...) the mounted
        // item ("CommodoreSoftwareFloppyResolver|GEOS 2.0 - WITH GEORAM SUPPORT") - the 4 digits come from it and
        // the file's name, the same in every session. (From the session folder's path they changed with each
        // session: the same disk got a new name, so ,W wrote it again instead of finding it there.) null: a
        // library file - its path is the same every time.
        public static string DriveName(string imagePath, string identity = null)
        {
            string baseName = new string(Path.GetFileNameWithoutExtension(imagePath ?? "")
                .ToUpperInvariant().Where(c => (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')).Take(7).ToArray());
            if (baseName.Length == 0) baseName = "DISK";
            string key = identity == null ? (imagePath ?? "") : identity + "|" + Path.GetFileName(imagePath ?? "");
            uint hash = 2166136261;                                    // FNV-1a over where it came from
            foreach (char c in key.ToUpperInvariant())
            {
                hash ^= c;
                hash *= 16777619;
            }
            return $"{baseName}-{(hash ^ (hash >> 16)) & 0xFFFF:X4}";
        }

        // A disk of a set on the drive: the disk number goes into the name, so the disks can be told apart
        // ("CALIFO1-8920", "CALIFO2-9F83"); a single disk keeps DriveName. 16 characters at most with ".D64".
        public static string DiskDriveName(IReadOnlyList<string> setPaths, int index, string identity = null)
        {
            if (setPaths.Count < 2) return DriveName(setPaths[index], identity);
            string full = DriveName(setPaths[index], identity);        // "CALIFOR-8920"
            string baseName = full.Substring(0, full.LastIndexOf('-'));
            if (baseName.Length > 6) baseName = baseName.Substring(0, 6);
            return baseName + (index + 1) + full.Substring(full.LastIndexOf('-'));
        }

        // The set's swap list: its base name and disk 1's code ("CALIFO-8920.LST")
        public static string SetListName(IReadOnlyList<string> setPaths, string identity = null)
        {
            string full = DriveName(setPaths[0], identity);
            int dash = full.LastIndexOf('-');
            string baseName = full.Substring(0, dash);
            if (baseName.Length > 6) baseName = baseName.Substring(0, 6);
            return baseName + full.Substring(dash) + ".LST";
        }

        private static void PutString(byte[] stub, int offset, string text)
        {
            byte[] bytes = System.Text.Encoding.ASCII.GetBytes(text);
            if (bytes.Length > WriteStringSize - 1) throw new ArgumentException("drive command too long: " + text);
            stub[2 + offset] = (byte)bytes.Length;
            Array.Copy(bytes, 0, stub, 2 + offset + 1, bytes.Length);
        }

        private static void AddSegment(List<byte> data, int address, byte[] bytes)
        {
            int count = (0x10000 - bytes.Length) & 0xFFFF;   // the stub counts up to 0
            data.Add((byte)(address & 0xFF));
            data.Add((byte)(address >> 8));
            data.Add((byte)(count & 0xFF));
            data.Add((byte)(count >> 8));
            data.AddRange(bytes);
        }
    }
