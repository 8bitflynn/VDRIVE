            string name = new string((folder ?? "").ToUpperInvariant().Where(c => (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_' || c == '-' || c == '.').ToArray());
            if (name.Length > 16) name = name.Substring(0, 16);
            return name.Length == 0 ? DefaultWriteFolder : name;
        }
